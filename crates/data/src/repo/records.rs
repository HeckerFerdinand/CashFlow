//! `public.payroll_records` and `public.time_records`: one row per employee and month.

use crate::database::Database;
use crate::error::{DataError, Result};
use crate::rest::Query;
use cashflow_core::payroll::{Calculation, Contributions};
use cashflow_core::{PayrollEntry, PayrollRecord, Period, Rates, TimeEntry, TimeRecord};
use chrono::NaiveDate;
use rust_decimal::Decimal;
use serde::{Deserialize, Serialize};
use std::collections::HashSet;
use uuid::Uuid;

const PAYROLL: &str = "payroll_records";
const TIME: &str = "time_records";
const PERIOD_KEY: &str = "employee_id,year,month";

fn period(year: i32, month: u32) -> Result<Period> {
    Period::new(year, month).map_err(|error| DataError::Decode(error.to_string()))
}

// -- Wage records ---------------------------------------------------------------

#[derive(Deserialize)]
struct PayrollRow {
    id: Uuid,
    employee_id: Uuid,
    year: i32,
    month: u32,
    statement_date: NaiveDate,
    base_pay: Decimal,
    extra_pay: Decimal,
    payout: Decimal,
    rate_health: Decimal,
    rate_pension: Decimal,
    rate_u1: Decimal,
    rate_u2: Decimal,
    rate_insolvency: Decimal,
    rate_flat_tax: Decimal,
    gross_total: Decimal,
    amount_health: Decimal,
    amount_pension: Decimal,
    amount_u1: Decimal,
    amount_u2: Decimal,
    amount_insolvency: Decimal,
    amount_flat_tax: Decimal,
    total_contribution: Decimal,
}

impl TryFrom<PayrollRow> for PayrollRecord {
    type Error = DataError;

    fn try_from(row: PayrollRow) -> Result<Self> {
        Ok(PayrollRecord {
            id: row.id,
            entry: PayrollEntry {
                employee_id: row.employee_id,
                period: period(row.year, row.month)?,
                statement_date: row.statement_date,
                base_pay: row.base_pay,
                extra_pay: row.extra_pay,
                payout: row.payout,
                rates: Rates {
                    health: row.rate_health,
                    pension: row.rate_pension,
                    u1: row.rate_u1,
                    u2: row.rate_u2,
                    insolvency: row.rate_insolvency,
                    flat_tax: row.rate_flat_tax,
                },
            },
            calculation: Calculation {
                gross_total: row.gross_total,
                contributions: Contributions {
                    health: row.amount_health,
                    pension: row.amount_pension,
                    u1: row.amount_u1,
                    u2: row.amount_u2,
                    insolvency: row.amount_insolvency,
                    flat_tax: row.amount_flat_tax,
                },
                total_contribution: row.total_contribution,
            },
        })
    }
}

