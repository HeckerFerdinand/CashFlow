/// Which months of a year already have wage / time records (for the overview).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct RecordedMonths {
    pub payroll: HashSet<(Uuid, u32)>,
    pub time: HashSet<(Uuid, u32)>,
}

impl RecordedMonths {
    pub fn has_payroll(&self, employee_id: Uuid, month: u32) -> bool {
        self.payroll.contains(&(employee_id, month))
    }

    pub fn has_time(&self, employee_id: Uuid, month: u32) -> bool {
        self.time.contains(&(employee_id, month))
    }
}

fn period_filter(employee_id: Uuid, period: Period) -> Query {
    Query::new().eq("employee_id", employee_id).eq("year", period.year()).eq("month", period.month())
}

fn year_filter(employee_id: Uuid, year: i32) -> Query {
    Query::new().eq("employee_id", employee_id).eq("year", year).order("month.asc")
}

impl Database {
    /// The wage record of one month, if recorded.
    pub async fn payroll_record(&self, employee_id: Uuid, period: Period) -> Result<Option<PayrollRecord>> {
        let row: Option<PayrollRow> =
            self.select_optional(PAYROLL, &period_filter(employee_id, period).select("*")).await?;
        row.map(PayrollRecord::try_from).transpose()
    }

    /// All wage records of one employee in one year, ordered by month.
    pub async fn payroll_records_of_year(&self, employee_id: Uuid, year: i32) -> Result<Vec<PayrollRecord>> {
        let rows: Vec<PayrollRow> = self.select(PAYROLL, &year_filter(employee_id, year).select("*")).await?;
        rows.into_iter().map(PayrollRecord::try_from).collect()
    }

    /// Creates or replaces the wage record of the entry's month.
    pub async fn save_payroll(&self, entry: &PayrollEntry) -> Result<PayrollRecord> {
        let row: PayrollRow =
            self.upsert(PAYROLL, PERIOD_KEY, &PayrollWrite::from(entry)).await.map_err(missing_employee)?;
        row.try_into()
    }

    pub async fn delete_payroll_record(&self, id: Uuid) -> Result<()> {
        match self.delete(PAYROLL, &Query::new().eq("id", id)).await? {
            0 => Err(DataError::NotFound),
            _ => Ok(()),
        }
    }

    /// The time record of one month, if recorded.
    pub async fn time_record(&self, employee_id: Uuid, period: Period) -> Result<Option<TimeRecord>> {
        let row: Option<TimeRow> = self.select_optional(TIME, &period_filter(employee_id, period).select("*")).await?;
        row.map(TimeRecord::try_from).transpose()
    }

    /// All time records of one employee in one year, ordered by month.
    pub async fn time_records_of_year(&self, employee_id: Uuid, year: i32) -> Result<Vec<TimeRecord>> {
        let rows: Vec<TimeRow> = self.select(TIME, &year_filter(employee_id, year).select("*")).await?;
        rows.into_iter().map(TimeRecord::try_from).collect()
    }

    /// Creates or replaces the time record of the entry's month.
    pub async fn save_time(&self, entry: &TimeEntry) -> Result<TimeRecord> {
        let row: TimeRow = self.upsert(TIME, PERIOD_KEY, &TimeWrite::from(entry)).await.map_err(missing_employee)?;
        row.try_into()
    }

    pub async fn delete_time_record(&self, id: Uuid) -> Result<()> {
        match self.delete(TIME, &Query::new().eq("id", id)).await? {
            0 => Err(DataError::NotFound),
            _ => Ok(()),
        }
    }

    /// Recorded months of all employees in `year` (two small requests).
    pub async fn recorded_months(&self, year: i32) -> Result<RecordedMonths> {
        #[derive(Deserialize)]
        struct Month {
            employee_id: Uuid,
            month: u32,
        }
        let query = Query::new().select("employee_id,month").eq("year", year);
        let payroll: Vec<Month> = self.select(PAYROLL, &query).await?;
        let time: Vec<Month> = self.select(TIME, &query).await?;
        Ok(RecordedMonths {
            payroll: payroll.into_iter().map(|m| (m.employee_id, m.month)).collect(),
            time: time.into_iter().map(|m| (m.employee_id, m.month)).collect(),
        })
    }
}

fn missing_employee(error: DataError) -> DataError {
    match error {
        DataError::Reference(_) => DataError::Reference("Der Mitarbeiter existiert nicht mehr.".into()),
        other => other,
    }
}
